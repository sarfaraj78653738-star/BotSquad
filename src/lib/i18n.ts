export function t(lang: Language, key: string): string {
  return STRINGS[lang]?.[key] ?? SCREEN_STRINGS[lang]?.[key] ?? CHAT_STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? SCREEN_STRINGS.en[key] ?? CHAT_STRINGS.en[key] ?? key;
}

// Agent file-tool approval summaries arrive as "Write <path>" /
// "Edit <path>" / "Delete <path>" plus the fixed delete preview.
// Translate the verb + preview at the card, so the agent lib (which
// has no language context) stays untouched and tool results sent to
// the model stay English.
export function translateApproval(lang: Language, summary: string, preview: string): { summary: string; preview: string } {
  let s = summary;
  if (s.startsWith('Write ')) s = `${t(lang, 'writeFile')} ${s.slice(6)}`;
  else if (s.startsWith('Edit ')) s = `${t(lang, 'editFile')} ${s.slice(5)}`;
  else if (s.startsWith('Delete ')) s = `${t(lang, 'deleteFile')} ${s.slice(7)}`;
  const p = preview === 'This file will be removed from the workspace.' ? t(lang, 'fileWillBeRemoved') : preview;
  return { summary: s, preview: p };
}

